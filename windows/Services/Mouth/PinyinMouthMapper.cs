    private bool _fallbackLogged;

    /// <summary>返回某个汉字的韵母分类；表外汉字返回 Unknown 并记录一次回退日志。</summary>
    public FinalCategory GetFinalCategory(char ch)
    {
        if (FinalTable.TryGetValue(ch, out var final))
        {
            return final switch
            {
                "A" => FinalCategory.A,
                "O" => FinalCategory.O,
                "E" => FinalCategory.E,
                "I" => FinalCategory.I,
                "U" => FinalCategory.U,
                _ => FinalCategory.Unknown
            };
        }

        if (!_fallbackLogged)
        {
            _fallbackLogged = true;
            AppLog.Warn("PINYIN_FALLBACK char_table_miss 已回退为按字符自然开合");
        }
        return FinalCategory.Unknown;
    }

    public bool IsClosedInit(char ch) => ClosedInitChars.Contains(ch);

    public bool IsSoftInit(char ch) => SoftInitChars.Contains(ch);

    /// <summary>按韵母分类返回基础嘴型（含幅度随机变化）。</summary>
    public MouthShape GetShape(FinalCategory category, double random01)
    {
        var (lo, hi, formLo, formHi) = category switch
        {
            FinalCategory.A => (0.75, 1.00, 0.10, 0.35),
            FinalCategory.O => (0.55, 0.80, -0.40, -0.70),
            FinalCategory.E => (0.40, 0.65, -0.10, -0.30),
            FinalCategory.I => (0.20, 0.45, 0.30, 0.60),
            FinalCategory.U => (0.30, 0.60, -0.40, -0.75),
            _ => (0.35, 0.65, -0.05, 0.05)
        };
        double openY = lo + (hi - lo) * random01;
        double form = formLo + (formHi - formLo) * random01;
        return new MouthShape(openY, form);
    }
