  bool _fallbackLogged = false;

  /// 返回某个汉字的韵母分类；表外汉字返回 unknown 并记录一次回退日志。
  FinalCategory getFinalCategory(String ch) {
    final finalChar = _finalTable[ch];
    if (finalChar != null) {
      switch (finalChar) {
        case 'A':
          return FinalCategory.a;
        case 'O':
          return FinalCategory.o;
        case 'E':
          return FinalCategory.e;
        case 'I':
          return FinalCategory.i;
        case 'U':
          return FinalCategory.u;
      }
    }
    if (!_fallbackLogged) {
      _fallbackLogged = true;
      // 表外汉字回退为自然开合
    }
    return FinalCategory.unknown;
  }

  bool isClosedInit(String ch) => _closedInitChars.contains(ch);

  bool isSoftInit(String ch) => _softInitChars.contains(ch);

  /// 按韵母分类返回基础嘴型（含幅度随机变化）。
  MouthShape getShape(FinalCategory category, double random01) {
    final (double lo, double hi, double formLo, double formHi) =
        switch (category) {
      FinalCategory.a => (0.75, 1.00, 0.10, 0.35),
      FinalCategory.o => (0.55, 0.80, -0.40, -0.70),
      FinalCategory.e => (0.40, 0.65, -0.10, -0.30),
      FinalCategory.i => (0.20, 0.45, 0.30, 0.60),
      FinalCategory.u => (0.30, 0.60, -0.40, -0.75),
      FinalCategory.unknown => (0.35, 0.65, -0.05, 0.05),
    };
    final openY = lo + (hi - lo) * random01;
    final form = formLo + (formHi - formLo) * random01;
    return MouthShape(openY, form);
  }
