"""Build the common-glyph subset of the Aliya serif font.

Output: ui/assets/fonts/NotoSerifSC-common.woff2 and ui/src/styles/serif-font.css with both faces of 'Aliya Serif'. Characters outside the
subset fall back to the full NotoSerifSC-var.ttf, so the full font is only fetched when a
rare glyph actually appears. Browsers match same-family faces in reverse declaration
order, so the subset face must come after the full one.

Usage: python scripts/subset-serif-font.py   (requires fonttools + brotli)
"""
import glob
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, 'ui')
FULL = os.path.join(UI, 'assets', 'fonts', 'NotoSerifSC-var.ttf')
OUT = os.path.join(UI, 'assets', 'fonts', 'NotoSerifSC-common.woff2')
CSS = os.path.join(UI, 'src', 'styles', 'serif-font.css')


def gb2312_chars() -> set[str]:
    chars = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.add(bytes([hi, lo]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return chars


def ranges(cps: list[int]) -> str:
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c
            continue
        out.append((start, prev))
        start = prev = c
    out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def main() -> None:
    chars = gb2312_chars()
    for path in glob.glob(os.path.join(UI, 'assets', 'dialogue', '**', '*.json'), recursive=True):
        with open(path, encoding='utf-8') as f:
            chars |= set(f.read())
    wanted = {ord(c) for c in chars}
    wanted |= set(range(0x20, 0x7F)) | set(range(0x2000, 0x2070))
    wanted |= set(range(0x3000, 0x3040)) | set(range(0xFF00, 0xFFF0))

    opts = subset.Options()
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.flavor = 'woff2'
    font = TTFont(FULL)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=wanted)
    subsetter.subset(font)
    covered = sorted(font.getBestCmap().keys())
    subset.save_font(font, OUT, opts)

    with open(CSS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by scripts/subset-serif-font.py; do not edit. OFL: /fonts/OFL.txt */\n')
        f.write('@font-face {\n')
        f.write("  font-family: 'Aliya Serif';\n")
        f.write("  src: url('/fonts/NotoSerifSC-var.ttf') format('truetype-variations');\n")
        f.write('  font-weight: 100 900;\n  font-style: normal;\n  font-display: swap;\n}\n')
        f.write('@font-face {\n')
        f.write("  font-family: 'Aliya Serif';\n")
        f.write("  src: url('/fonts/NotoSerifSC-common.woff2') format('woff2-variations');\n")
        f.write('  font-weight: 100 900;\n  font-style: normal;\n  font-display: swap;\n')
        f.write(f'  unicode-range: {ranges(covered)};\n}}\n')
    sys.stdout.write(f'{len(covered)} glyphs, {os.path.getsize(OUT)} bytes\n')


if __name__ == '__main__':
    main()
